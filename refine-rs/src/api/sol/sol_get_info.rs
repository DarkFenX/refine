use crate::{Sol, SolInfo, SolInfoCmd};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl Sol<'_> {
    #[tracing::instrument(name = "sol-inf", level = "error", skip_all)]
    pub async fn get_info(&mut self, info_cmd: SolInfoCmd) -> SolInfo {
        self.internal_get_info(info_cmd).await
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Private
////////////////////////////////////////////////////////////////////////////////////////////////////
impl Sol<'_> {
    pub(crate) async fn internal_get_info(&mut self, info_cmd: SolInfoCmd) -> SolInfo {
        // Variables for move
        let ctx = self.get_ctx();
        self.exec_standard_infallible(move |core_sol| info_cmd.execute(ctx.sol_id, ctx.src_alias, core_sol))
            .await
    }
}
