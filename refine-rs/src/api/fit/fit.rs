use crate::{FitId, Sol};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
pub struct Fit<'r, 's> {
    pub(super) sol: &'s mut Sol<'r>,
    pub(super) id: FitId,
}
impl<'r, 's> Fit<'r, 's> {
    pub fn get_id(&self) -> FitId {
        self.id
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Private
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'r, 's> Fit<'r, 's> {
    pub(super) fn new(sol: &'s mut Sol<'r>, id: FitId) -> Self {
        Self { sol, id }
    }
}
