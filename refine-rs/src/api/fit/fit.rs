use crate::{FitId, Sol};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
pub struct Fit<'refine, 'sol> {
    pub(super) sol: &'sol mut Sol<'refine>,
    pub(super) id: FitId,
}
impl<'refine, 'sol> Fit<'refine, 'sol> {
    pub fn get_id(&self) -> FitId {
        self.id
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Private
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'refine, 'sol> Fit<'refine, 'sol> {
    pub(super) fn new(sol: &'sol mut Sol<'refine>, id: FitId) -> Self {
        Self { sol, id }
    }
}
