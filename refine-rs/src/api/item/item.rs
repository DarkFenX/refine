use crate::{ItemId, Sol};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
pub struct Item<'refine, 'sol> {
    pub(super) sol: &'sol mut Sol<'refine>,
    pub(super) id: ItemId,
}
impl<'refine, 'sol> Item<'refine, 'sol> {
    pub fn get_id(&self) -> ItemId {
        self.id
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Private
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'refine, 'sol> Item<'refine, 'sol> {
    pub(super) fn new(sol: &'sol mut Sol<'refine>, id: ItemId) -> Self {
        Self { sol, id }
    }
}
