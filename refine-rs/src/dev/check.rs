use crate::SolarSystem;

////////////////////////////////////////////////////////////////////////////////////////////////////
// API
////////////////////////////////////////////////////////////////////////////////////////////////////
impl SolarSystem<'_> {
    #[tracing::instrument(name = "sol-chk", level = "trace", skip_all)]
    pub async fn dev_consistency_check(&mut self, dev_cmd: DecCheckCmd) -> bool {
        self.exec_standard_safe(move |core_sol| dev_cmd.execute(core_sol)).await
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Command
////////////////////////////////////////////////////////////////////////////////////////////////////
#[derive(Default)]
pub struct DecCheckCmd;

////////////////////////////////////////////////////////////////////////////////////////////////////
// Command - construction
////////////////////////////////////////////////////////////////////////////////////////////////////
impl DecCheckCmd {
    pub fn new() -> Self {
        Self
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Command - execution
////////////////////////////////////////////////////////////////////////////////////////////////////
impl DecCheckCmd {
    pub(crate) fn execute(self, core_sol: &mut rc::SolarSystem) -> bool {
        core_sol.consistency_check()
    }
}
