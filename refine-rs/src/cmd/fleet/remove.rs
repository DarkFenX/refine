use crate::cmd::{RemoveFleetError, basic::FleetRemoveCmdICtx};

#[derive(Default)]
pub struct RemoveFleetCmd {
    basic: FleetRemoveCmdICtx,
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Construction
////////////////////////////////////////////////////////////////////////////////////////////////////
impl RemoveFleetCmd {
    pub fn new() -> Self {
        Self::default()
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Execution
////////////////////////////////////////////////////////////////////////////////////////////////////
impl RemoveFleetCmd {
    pub(crate) fn execute(
        &self,
        core_sol: &mut rc::SolarSystem,
        fleet_id: &rc::FleetId,
    ) -> Result<(), RemoveFleetError> {
        self.basic.execute(core_sol, fleet_id)
    }
}
