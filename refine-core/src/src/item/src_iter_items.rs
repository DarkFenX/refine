use crate::{Src, src::SrcItem};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl Src {
    /// Mutated item types are not included.
    pub fn iter_items(&self) -> impl ExactSizeIterator<Item = SrcItem<'_>> {
        self.r_data.iter_items().map(|r_item| SrcItem::new(r_item))
    }
}
