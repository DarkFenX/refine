use crate::{EntityIter, Fit, Sol};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl Sol {
    pub fn iter_fits(&mut self) -> EntityIter<'_, Fit<'_>> {
        let core = self.inner_mut();
        let fit_uids = core.u_data.fits.keys().collect();
        EntityIter::new(core, fit_uids)
    }
}
