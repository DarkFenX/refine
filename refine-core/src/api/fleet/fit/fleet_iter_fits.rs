use crate::{EntityIter, Fit, Fleet};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fleet<'s> {
    pub fn iter_fits(&mut self) -> EntityIter<'_, Fit<'_>> {
        let fit_uids = self.core.u_data.fleets.get(self.uid).iter_fits().collect();
        EntityIter::new(self.core, fit_uids)
    }
}
