use crate::{EntityIter, Fleet, Sol};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl Sol {
    pub fn iter_fleets(&mut self) -> EntityIter<'_, Fleet<'_>> {
        let core = self.inner_mut();
        let fleet_uids = core.u_data.fleets.keys().collect();
        EntityIter::new(core, fleet_uids)
    }
}
