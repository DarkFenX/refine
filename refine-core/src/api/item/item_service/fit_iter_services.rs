use crate::{EntityIter, Fit, Service};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fit<'s> {
    pub fn iter_services(&mut self) -> EntityIter<'_, Service<'_>> {
        let service_uids = self.core.u_data.fits.get(self.uid).services.iter().copied().collect();
        EntityIter::new(self.core, service_uids)
    }
}
