use crate::{Fit, Ship};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fit<'s> {
    pub fn get_ship(&mut self) -> Option<Ship<'_>> {
        self.core
            .u_data
            .fits
            .get(self.uid)
            .ship
            .map(|ship_uid| Ship::new(self.core, ship_uid))
    }
}
