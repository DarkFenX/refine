use crate::{EntityIter, Fit, Implant};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fit<'s> {
    pub fn iter_implants(&mut self) -> EntityIter<'_, Implant<'_>> {
        let implant_uids = self.core.u_data.fits.get(self.uid).implants.iter().copied().collect();
        EntityIter::new(self.core, implant_uids)
    }
}
