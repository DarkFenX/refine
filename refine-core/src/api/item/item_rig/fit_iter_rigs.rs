use crate::{EntityIter, Fit, Rig};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fit<'s> {
    pub fn iter_rigs(&mut self) -> EntityIter<'_, Rig<'_>> {
        let rig_uids = self.core.u_data.fits.get(self.uid).rigs.iter().copied().collect();
        EntityIter::new(self.core, rig_uids)
    }
}
