use crate::{EntityIter, Fit, Rig};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'sol> Fit<'sol> {
    pub fn iter_rigs(&mut self) -> EntityIter<'_, Rig<'_>> {
        let rig_uids = self.sol.u_data.fits.get(self.uid).rigs.iter().copied().collect();
        EntityIter::new(self.sol, rig_uids)
    }
}
