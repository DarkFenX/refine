use crate::{ItemId, sol::SolCore, ud::UItemId};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
/// Stats of an item.
pub struct ItemStats<'s> {
    pub(in crate::api) sol: &'s mut SolCore,
    pub(in crate::api) uid: UItemId,
}
impl<'s> ItemStats<'s> {
    pub fn get_item_id(&self) -> ItemId {
        self.sol.u_data.items.ext_id_by_int_id(self.uid)
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Private
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> ItemStats<'s> {
    pub(in crate::api) fn new(sol: &'s mut SolCore, uid: UItemId) -> Self {
        Self { sol, uid }
    }
}
