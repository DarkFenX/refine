use crate::{Booster, EntityIter, Fit};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fit<'s> {
    pub fn iter_boosters(&mut self) -> EntityIter<'_, Booster<'_>> {
        let booster_uids = self.core.u_data.fits.get(self.uid).boosters.iter().copied().collect();
        EntityIter::new(self.core, booster_uids)
    }
}
