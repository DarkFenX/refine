use crate::{EntityIter, Fit, Item};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fit<'s> {
    pub fn iter_items(&mut self) -> EntityIter<'_, Item<'_>> {
        let item_uids = self.sol.u_data.get_fit_item_uids(self.uid);
        EntityIter::new(self.sol, item_uids)
    }
}
