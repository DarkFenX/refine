use crate::{Fit, Stance};

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public
////////////////////////////////////////////////////////////////////////////////////////////////////
impl<'s> Fit<'s> {
    pub fn get_stance(&mut self) -> Option<Stance<'_>> {
        self.core
            .u_data
            .fits
            .get(self.uid)
            .stance
            .map(|stance_uid| Stance::new(self.core, stance_uid))
    }
}
